#ifndef _ERRNO_H
#define _ERRNO_H

// Errors (4.4BSD-Lite2)
#define EPERM 0x1       // Operation not permitted
#define ENOENT 0x2      // No such file or directory

#define EIO 0x5         // Input/output error
#define ENOMEM 0x12     // Cannot allocate memory
#define EINVAL 0x22     // Invalid argument
#define EBUSY 0x16

#endif
